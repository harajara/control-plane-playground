// Command generate asks godog what step definitions its feature files need and
// writes them as Go stubs.
//
// It runs godog over features/ with an empty scenario initializer, so every
// step comes back undefined, and godog prints the snippets it suggests: a
// function per step and a registration per regex. Those become
// tests/bdd/steps_generated.go. A handler is emitted as a pending stub only
// while no hand-written file defines it, so implementing a step is permanent
// and regenerating stays useful after the feature files grow.
package main

import (
	"bytes"
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"regexp"
	"sort"
	"strings"

	"github.com/cucumber/godog"
)

var (
	stepLine = regexp.MustCompile("ctx\\.Step\\(`([^`]+)`, (\\w+)\\)")
	funcLine = regexp.MustCompile(`(?m)^func (\w+)\(([^)]*)\) error \{`)
)

type step struct {
	regex, fn, params string
}

func main() {
	// Paths are relative to the repository root, which is where
	// `task bdd:stubs` runs the generator.
	features := flag.String("features", "features", "feature files or directory")
	pkg := flag.String("package", filepath.Join("tests", "bdd"), "package directory to scan for implementations")
	out := flag.String("out", filepath.Join("tests", "bdd", "steps_generated.go"), "file to write")
	flag.Parse()
	if err := run(*features, *pkg, *out); err != nil {
		fmt.Fprintln(os.Stderr, "generate failed:", err)
		os.Exit(1)
	}
}

func run(features, pkg, out string) error {
	var buf bytes.Buffer
	suite := godog.TestSuite{
		Name:                "generate",
		ScenarioInitializer: func(s *godog.ScenarioContext) {},
		Options: &godog.Options{
			Format:   "pretty",
			Paths:    []string{features},
			NoColors: true,
			Strict:   false,
			Output:   &buf,
		},
	}
	suite.Run()
	text := buf.String()
	if !strings.Contains(text, "ctx.Step(") {
		return fmt.Errorf("godog printed no step definitions; check that %s contains feature files", features)
	}

	// Signatures come from godog's own snippet functions.
	params := map[string]string{}
	for _, m := range funcLine.FindAllStringSubmatch(text, -1) {
		params[m[1]] = m[2]
	}
	seen := map[string]bool{}
	steps := []step{}
	for _, m := range stepLine.FindAllStringSubmatch(text, -1) {
		regex, fn := m[1], m[2]
		if seen[regex] {
			continue
		}
		seen[regex] = true
		steps = append(steps, step{regex: regex, fn: fn, params: params[fn]})
	}
	sort.Slice(steps, func(i, j int) bool { return steps[i].regex < steps[j].regex })

	implemented, err := implementedIn(pkg)
	if err != nil {
		return err
	}
	missing := []step{}
	for _, st := range steps {
		if !implemented[st.fn] {
			missing = append(missing, st)
		}
	}

	var body bytes.Buffer
	body.WriteString("// Code generated by \"task bdd:stubs\" from features/*.feature. DO NOT EDIT.\n")
	body.WriteString("// Regenerate with: task bdd:stubs\n\n")
	body.WriteString("//go:build bdd\n\npackage bdd\n\n")
	if len(missing) > 0 {
		body.WriteString("import (\n\t\"context\"\n\n\t\"github.com/cucumber/godog\"\n)\n\n")
	} else {
		body.WriteString("import \"github.com/cucumber/godog\"\n\n")
	}
	body.WriteString("// registerSteps binds every step written in the feature files to a handler.\n")
	body.WriteString("// Handlers live in the hand-written steps_*.go files beside this one. A step\n")
	body.WriteString("// with no implementation stays here as a pending stub, which fails the suite\n")
	body.WriteString("// in strict mode rather than passing silently.\n")
	body.WriteString("func registerSteps(s *godog.ScenarioContext) {\n")
	for _, st := range steps {
		fmt.Fprintf(&body, "\ts.Step(`%s`, %s)\n", st.regex, st.fn)
	}
	body.WriteString("}\n")

	if len(missing) > 0 {
		body.WriteString("\n// Pending stubs. Implement each one in a steps_*.go file and run\n")
		body.WriteString("// task bdd:stubs again to drop it from this list.\n")
		for _, st := range missing {
			sig := "ctx context.Context"
			if st.params != "" {
				sig += ", " + st.params
			}
			fmt.Fprintf(&body, "\nfunc %s(%s) error {\n\treturn godog.ErrPending\n}\n", st.fn, sig)
		}
	}
	if err := os.WriteFile(out, body.Bytes(), 0o644); err != nil {
		return err
	}
	fmt.Printf("%s: %d steps registered, %d implemented, %d pending\n", out, len(steps), len(steps)-len(missing), len(missing))
	return nil
}

// implementedIn collects function names declared in non-generated Go files of
// a package directory.
func implementedIn(dir string) (map[string]bool, error) {
	out := map[string]bool{}
	files, err := filepath.Glob(filepath.Join(dir, "*.go"))
	if err != nil {
		return nil, err
	}
	decl := regexp.MustCompile(`(?m)^func (\w+)\(`)
	for _, f := range files {
		if strings.Contains(f, "steps_generated.go") {
			continue
		}
		b, err := os.ReadFile(f)
		if err != nil {
			return nil, err
		}
		for _, m := range decl.FindAllStringSubmatch(string(b), -1) {
			out[m[1]] = true
		}
	}
	return out, nil
}
